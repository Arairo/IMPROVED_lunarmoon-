const { chromium } = require('playwright');
const OUT = '/tmp/claude-0/promo/cap/';
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 2 });
  await ctx.addInitScript(() => { try { localStorage.setItem('lsp.proWelcome2', '1'); localStorage.setItem('lsp.cmpWelcome', '1'); localStorage.setItem('lsp.controlsSeen', '1'); localStorage.setItem('lsp.theme', 'dark'); localStorage.setItem('lsp.sound', 'off'); localStorage.setItem('lsp.cmpTourSeen', '1'); } catch {} });
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:5180/?k=1#pro', { waitUntil: 'networkidle' }); await p.waitForTimeout(4500);
  await p.evaluate(() => document.querySelector('.xp-mode-hint')?.classList.remove('is-on'));
  await p.click('[data-go="1"]'); await p.waitForTimeout(700);
  await p.evaluate(() => document.querySelector('.xp-flow .f-body').scrollTo(0, 420)); await p.waitForTimeout(300);
  await p.screenshot({ path: OUT + 'find0.png' });
  await p.click('[data-find]'); await p.waitForTimeout(900);
  await p.evaluate(() => document.querySelector('.xp-flow .f-body').scrollTo(0, 420)); await p.waitForTimeout(300);
  await p.screenshot({ path: OUT + 'find1.png' });
  await p.click('[data-x="help"]'); await p.waitForTimeout(500);
  await p.screenshot({ path: OUT + 'help.png' });
  await p.keyboard.press('Escape');
  await p.click('[data-x="settings"]'); await p.waitForTimeout(500);
  await p.screenshot({ path: OUT + 'settings.png' });
  await p.keyboard.press('Escape');
  await p.click('#modeCompareBtn'); await p.waitForTimeout(400);
  await p.click('[data-q="slip"]'); await p.waitForTimeout(300);
  await p.selectOption('#cmpAddSiteSel', 'peak-shackleton'); await p.waitForTimeout(1500);
  await p.screenshot({ path: OUT + 'cmp1.png' });
  await p.evaluate(() => document.querySelector('.cl-bars').scrollIntoView()); await p.waitForTimeout(1300);
  await p.screenshot({ path: OUT + 'cmp2.png' });
  console.log('errors', errs); await b.close();
})();
